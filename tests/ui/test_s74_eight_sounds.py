"""S-74 — Eight sounds on eight events, and nine plays on the eight actions.

docs/E2E.md §6 S-74. Fixture F2. Required by AC-118. Serves Stage 2.

The eight assets are `RESEARCH.md` §3's observed list, generated by `tools/make_sounds.py` into
`web/public/sounds/` and shipped verbatim by Vite. `web/src/lib/sound.ts` is the whole play layer;
the call sites are `GoalCard.vue`, `GoalCardTools.vue` and `Column.vue`.

Nine plays across eight assets, not eight: action 8 is itself a check, so it fires `checked` and
then `all_completed`. S-74's own words — "asserting eight entries would fail a correct build".
`ACCEPTANCE.md` AC-118 still says eight; the correction is filed with the owner, and this file
follows S-74.

One deviation from S-74's step table is forced by the fixture and reported as a doc row rather
than papered over:

 1. **Steps 6 and 7 target `SYNMAY02`, not `SYNDAY01`.** S-74 asks for expand (6) then collapse
    (7) on `SYNDAY01`, then a check on `SYNSUB03` (8) — but `SYNSUB03` is drawn *inside*
    `SYNDAY01` and nowhere else (`store.ts::toCardData` nests vertical-NULL children only), so a
    collapsed `SYNDAY01` puts step 8's target in no DOM at all. The two steps cannot both hold on
    one card. Setup here gives `SYNMAY02` a nested child so it has a toggle of its own, leaving
    `SYNDAY01` expanded for step 8.
Parent cards ship collapsed, matching the reference measured in P-31. Setup therefore expands
`SYNDAY01` before recording so step 8's child is present; `SYNMAY02` remains untouched and
collapsed, making step 6's first click the required expand event. The recorder is cleared at the
line where step 1 begins.

Instrumentation entry 2 of E2E.md §1 (the audio recorder) is installed here rather than in
`tests/ui/conftest.py`: this is the only scenario in the package that touches audio, and the
conftest's own docstring states the recorder belongs with the scenario that justifies it.
"""

