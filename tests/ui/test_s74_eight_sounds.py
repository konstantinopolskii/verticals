# Entry 2 of E2E.md §1: patch `HTMLMediaElement.prototype.play` to append `this.currentSrc` to
# `window.__audio`. Installed before app load so a play fired during boot is recorded too — S-74
# asserts `window.__audio` is empty after page load alone, which is only checkable if a boot-time
# play would have been caught.
_AUDIO_RECORDER_SCRIPT = """
(function () {
  window.__audio = [];
  var realPlay = HTMLMediaElement.prototype.play;
  HTMLMediaElement.prototype.play = function () {
    window.__audio.push(this.currentSrc || this.src || '');
    return realPlay.apply(this, arguments);
  };
})();
"""

